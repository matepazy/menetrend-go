"""Generate MenetrendGO SVG masters and Android vectors from identical paths.

Run from any directory: python scripts/generate_branding.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRANDING = ROOT / "branding"
RES = ROOT / "app/src/main/res"
BLUE = "#2864D9"

# Reconstructed as clean geometry from the approved train concept, not a bitmap trace.
# The window and headlights are transparent cutouts (even-odd fill).
BODY = (
    "M40,23 H68 Q78,23 78,33 V63 Q78,73 68,73 H40 Q30,73 30,63 V33 Q30,23 40,23 Z "
    "M39.5,31 H68.5 Q73,31 73,35.5 V47.5 Q73,52 68.5,52 H39.5 Q35,52 35,47.5 "
    "V35.5 Q35,31 39.5,31 Z "
    "M44.8,62.5 A4,4 0,1 0,36.8,62.5 A4,4 0,1 0,44.8,62.5 Z "
    "M71.2,62.5 A4,4 0,1 0,63.2,62.5 A4,4 0,1 0,71.2,62.5 Z"
)
RAILS = (
    "M38.2,74.6 H41.4 Q43.8,74.6 42.2,76.5 L36.3,84.2 Q35.6,85.2 34.2,85.2 "
    "H30.8 Q28.5,85.2 30,83.4 L36.4,75.4 Q37,74.6 38.2,74.6 Z "
    "M69.8,74.6 H66.6 Q64.2,74.6 65.8,76.5 L71.7,84.2 Q72.4,85.2 73.8,85.2 "
    "H77.2 Q79.5,85.2 78,83.4 L71.6,75.4 Q71,74.6 69.8,74.6 Z"
)
# 108dp adaptive layer, optically centered. All painted pixels fit in a 66dp
# diameter safe circle, including the rails. The visible mask is about 72dp.
TRANSFORM = "translate(9.72 9.638) scale(0.82)"


def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(line.rstrip() for line in content.splitlines()) + "\n", encoding="utf-8")


def svg(name: str, color: str, background: str = "", adaptive: bool = False, mark: bool = False):
    viewbox = "24 18 60 72" if mark else "0 0 108 108" if adaptive else "18 18 72 72"
    transform = "" if mark else f' transform="{TRANSFORM}"'
    write(BRANDING / name, f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">
  <title>MenetrendGO</title>
  {background}
  <g fill="{color}"{transform}>
    <path fill-rule="evenodd" d="{BODY}"/>
    <path d="{RAILS}"/>
  </g>
</svg>''')


def vector(name: str, size: int = 108, scale: str = "0.82", x: str = "9.72", y: str = "9.638"):
    write(RES / "drawable" / name, f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_branding.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="{size}" android:viewportHeight="{size}">
    <group android:translateX="{x}" android:translateY="{y}" android:scaleX="{scale}" android:scaleY="{scale}">
        <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="{BODY}" />
        <path android:fillColor="#FFFFFF" android:pathData="{RAILS}" />
    </group>
</vector>''')


svg("menetrendgo-mark.svg", BLUE, mark=True)
svg("menetrendgo-mark-white.svg", "#FFFFFF", mark=True)
svg("menetrendgo-icon.svg", "#FFFFFF", f'<path fill="{BLUE}" d="M18,18 H90 V90 H18 Z"/>')
svg("menetrendgo-icon-rounded.svg", "#FFFFFF", f'<rect x="18" y="18" width="72" height="72" rx="16" fill="{BLUE}"/>')
svg("menetrendgo-icon-round.svg", "#FFFFFF", f'<circle cx="54" cy="54" r="36" fill="{BLUE}"/>')
svg("menetrendgo-launcher-foreground.svg", "#FFFFFF", adaptive=True)
vector("ic_launcher_foreground.xml")
# The same train fits the 24dp notification canvas with a 2dp vertical margin.
vector("ic_notification.xml", size=24, scale="0.32", x="-5.28", y="-5.312")
write(RES / "values" / "icon_colors.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{BLUE}</color>
</resources>''')

# Both launcher entries use the same safe artwork; the launcher supplies its mask.
# minSdk is 28, so every supported device understands adaptive icons.
for qualifier, monochrome in (("mipmap-anydpi-v26", False), ("mipmap-anydpi-v33", True)):
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        themed = '\n    <monochrome android:drawable="@drawable/ic_launcher_foreground" />' if monochrome else ""
        write(RES / qualifier / name, f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_branding.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />{themed}
</adaptive-icon>''')
